const SEVERITY_ORDER = { critical: 0, high: 1, medium: 2, info: 3 };
export const severityRank = (s) => SEVERITY_ORDER[s] ?? 4;
export const worstSeverity = (list) =>
  list.reduce((acc, s) => (severityRank(s) < severityRank(acc) ? s : acc), 'info');

/**
 * Находит запись каталога по причине WB.
 * @param {string} reason  bonusTypeName (или sellerOperName, если причина пуста)
 * @param {string} [kind]  ограничить поиск видом удержания
 */
export function classify(reason, kind) {
  const text = String(reason || '').trim();
  if (!text) return null;
  for (const item of CATALOG) {
    if (kind && item.kind !== kind && !(kind === 'logistics' && item.kind === 'logistics-forward')) continue;
    if (item.match.test(text)) return item;
  }
  return null;
}

/** Известна ли причина каталогу (для правила «новый тип удержания»). */
export const isKnown = (reason, kind) => Boolean(classify(reason, kind));

export const byId = (id) => CATALOG.find((c) => c.id === id) || null;
